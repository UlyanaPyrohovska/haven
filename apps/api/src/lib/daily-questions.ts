export const DAILY_ANSWER_MAX_LENGTH = 150;

/** UTC day-of-year (1–366) from `YYYY-MM-DD`. */
export function dayOfYearUtc(date: string): number {
	const [year, month, day] = date.split("-").map(Number);
	const start = Date.UTC(year, month - 1, day);
	const yearStart = Date.UTC(year, 0, 0);

	return Math.floor((start - yearStart) / 86_400_000);
}

export function dailyQuestionIndex(date = utcToday()): number {
	return dayOfYearUtc(date) % DAILY_QUESTIONS.length;
}

export function dailyQuestion(date = utcToday()): string {
	return DAILY_QUESTIONS[dailyQuestionIndex(date)];
}
